"""
Cliente Tinfoil para Docker (con SDK: attestation + TLS pinning + EHBP).
Conecta directo a inference.tinfoil.sh. Sin tinfoil-gateway, sin nginx.
Funciones: llamar_gpt_oss, detectar_libro.
"""

import os
import json
import re
import time
import logging
from tinfoil import TinfoilAI

log = logging.getLogger(__name__)

TINFOIL_API_KEY = os.environ.get("TINFOIL_API_KEY", "")
MODEL_LLM = "gpt-oss-120b"

# SDK client (attestation + TLS pinning + EHBP, directo a inference.tinfoil.sh)
_tinfoil_client = TinfoilAI(api_key=TINFOIL_API_KEY, timeout=300)


def _strip_markdown_json(texto):
    """Elimina bloques markdown ```json ... ``` del texto."""
    return re.sub(r"```(?:json)?\s*|\s*```", "", texto).strip()


def _reintentar(func, *args, max_reintentos=3, espera_base=2, **kwargs):
    """Reintenta una llamada con backoff exponencial."""
    for intento in range(max_reintentos):
        try:
            return func(*args, **kwargs)
        except Exception as e:
            if intento == max_reintentos - 1:
                log.error("Reintento final (%d/%d) fallido: %s", max_reintentos, max_reintentos, e)
                raise
            espera = espera_base * (2 ** intento)
            log.warning("Reintento %d/%d: %s. Esperando %ds...", intento + 1, max_reintentos, e, espera)
            time.sleep(espera)


def llamar_gpt_oss(system_prompt, user_content, schema, temperatura=0.1, max_tokens=4096):
    """Llamada a GPT-OSS con structured outputs vía SDK Tinfoil."""
    payload_messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_content},
    ]

    def _call():
        response = _tinfoil_client.chat.completions.create(
            model=MODEL_LLM,
            messages=payload_messages,
            temperature=temperatura,
            max_tokens=max_tokens,
            response_format={
                "type": "json_schema",
                "json_schema": {
                    "name": "response",
                    "schema": schema,
                },
            },
            timeout=300,
        )
        contenido = response.choices[0].message.content
        if contenido is None:
            raise ValueError("GPT-OSS devolvió content=None")
        contenido = _strip_markdown_json(contenido)
        return json.loads(contenido)

    return _reintentar(_call)


SCHEMA_LIBRO = {
    "type": "object",
    "properties": {
        "libro_referenciado": {
            "type": "string",
            "description": "Name of the referenced book, or empty string if none."
        },
        "cita_aproximada": {
            "type": "string",
            "description": "Approximate quote from the book if one was recited, or empty string if none."
        }
    },
    "required": ["libro_referenciado", "cita_aproximada"]
}


def detectar_libro(transcripcion, catalogo_libros):
    """Detecta si el hablante referencia un libro y extrae la cita aproximada."""
    libros_str = "\n".join(f"- {libro}" for libro in catalogo_libros) if catalogo_libros else "(ninguno)"

    system_prompt = f"""You are a book detection assistant. The user may reference a book in their speech.
If they do, identify the book and the approximate quote they recited.

The speaker may switch between Spanish, English, and French within a single recording.

IMPORTANT: The transcription is generated by speech recognition (ASR) and may contain errors.
Proper nouns, especially non-English names, may be misheard. For example, "Nichiren" could be
transcribed as "Nietzsche", "Kierkegaard" as "Kierkeard", or even some other examples that cannot be determined, but expect crazy names that don't match descriptions. You have to infere the correct answer.

When the speaker says "in the book", "the book says", "the book mentions", or similar phrases,
they are referencing a book. They might be referencing a book even if they don't use these phrases, but whenever they do use these phrases or similar, they are referencing a book.
Match the spoken title to the catalog below using fuzzy matching.
A close phonetic match is sufficient — do not require exact title matches.

Available books:
{libros_str}

Return JSON: {{"libro_referenciado": "...", "cita_aproximada": "..."}}
If no book is referenced, return empty strings for both fields."""

    return llamar_gpt_oss(system_prompt, transcripcion[:8000], SCHEMA_LIBRO,
                          temperatura=0.1, max_tokens=2048)
